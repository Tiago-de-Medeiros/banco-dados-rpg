-- 1. CRIAÇÃO DO BANCO DE DADOS
CREATE DATABASE JogoRPG;

-- 2. SELEÇÃO DO BANCO DE DADOS PARA USO
USE JogoRPG;

-- 3. CRIAÇÃO DA TABELA USUARIOS
CREATE TABLE USUARIOS (
    UsuarioId INT AUTO_INCREMENT,
    Email VARCHAR(100) NOT NULL,
    Senha VARCHAR(255) NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (UsuarioId)
);

-- 4. CRIAÇÃO DA TABELA CLASSES
CREATE TABLE CLASSES (
    ClasseId INT AUTO_INCREMENT,
    Nome VARCHAR(50) NOT NULL,
    Descricao VARCHAR(255),
    CONSTRAINT PK_CLASSES PRIMARY KEY (ClasseId)
);

-- 5. CRIAÇÃO DA TABELA HABILIDADES
CREATE TABLE HABILIDADES (
    HabilidadeId INT AUTO_INCREMENT,
    Nome VARCHAR(50) NOT NULL,
    CONSTRAINT PK_HABILIDADES PRIMARY KEY (HabilidadeId)
);

-- 6. CRIAÇÃO DA TABELA PERSONAGENS
CREATE TABLE PERSONAGENS (
    PersonagemId INT AUTO_INCREMENT,
    NomePersonagem VARCHAR(50) NOT NULL,
    UsuarioId INT NOT NULL,
    ClasseId INT NOT NULL,
    CONSTRAINT PK_PERSONAGENS PRIMARY KEY (PersonagemId),
    CONSTRAINT FK_PERSONAGENS_USUARIOS FOREIGN KEY (UsuarioId) REFERENCES USUARIOS(UsuarioId),
    CONSTRAINT FK_PERSONAGENS_CLASSES FOREIGN KEY (ClasseId) REFERENCES CLASSES(ClasseId)
);

-- 7. CRIAÇÃO DA TABELA CLASSES_HABILIDADES
CREATE TABLE CLASSES_HABILIDADES (
    ClasseId INT NOT NULL,
    HabilidadeId INT NOT NULL,
    CONSTRAINT PK_CLASSES_HABILIDADES PRIMARY KEY (ClasseId, HabilidadeId),
    CONSTRAINT FK_CLASSES_HABILIDADES_CLASSES FOREIGN KEY (ClasseId) REFERENCES CLASSES(ClasseId),
    CONSTRAINT FK_CLASSES_HABILIDADES_HABILIDADES FOREIGN KEY (HabilidadeId) REFERENCES HABILIDADES(HabilidadeId)
);
